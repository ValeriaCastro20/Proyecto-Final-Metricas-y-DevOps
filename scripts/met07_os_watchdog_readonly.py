"""Read-only OS audit and independent MET-07 watchdog canary; never patches Kubernetes."""
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import time
import uuid

import met07 as core

WORDS = re.compile(r'\b(shutdown|reboot|poweroff|halt|deallocate)\b|Automatic-Reboot', re.I)


def run(args, timeout=10):
    try:
        p = subprocess.run(args, capture_output=True, text=True, timeout=timeout, check=False)
        return {'exit': p.returncode, 'stdout': p.stdout, 'stderr': p.stderr}
    except (OSError, subprocess.TimeoutExpired):
        return {'exit': None, 'stdout': '', 'stderr': 'unavailable_or_timeout'}


def summary(text):
    return {'sha256': hashlib.sha256(text.encode()).hexdigest(),
            'power_terms': sorted(set(m.group().lower() for m in WORDS.finditer(text)))}


def os_audit():
    timers = run(['systemctl', 'list-timers', '--all', '--no-pager', '--output=json'])
    result = {'material': 'REAL_READ_ONLY_OS_AUDIT', 'server_utc': core.utc(time.time()),
              'shutdown_scheduled_file_exists': Path('/run/systemd/shutdown/scheduled').exists(),
              'timer_list_exit': timers['exit'], 'timers': [], 'cron': [], 'at': {},
              'limits': ['Static inspection is not proof of absence of indirect custom scripts or external cloud automation.']}
    try:
        rows = json.loads(timers['stdout'])
    except ValueError:
        rows = []
        result['timer_list_parse_failed'] = True
    for row in rows:
        name = row['unit']
        shown = run(['systemctl', 'show', name, '--property=Unit,NextElapseUSecRealtime,NextElapseUSecMonotonic,ActiveState,FragmentPath,DropInPaths'])
        props = dict(line.split('=', 1) for line in shown['stdout'].splitlines() if '=' in line)
        target = props.get('Unit')
        service = run(['systemctl', 'show', target, '--property=ExecStart,ExecStartPre,ExecStartPost,FragmentPath,DropInPaths']) if target else {'exit': None, 'stdout': ''}
        definition = run(['systemctl', 'cat', name, *([target] if target else [])])
        result['timers'].append({'timer': name, 'listed_schedule': row, 'properties': props,
                                'show_exit': shown['exit'], 'service_show_exit': service['exit'],
                                'service_commands': summary(service['stdout']),
                                'definition_read_exit': definition['exit'], 'definition': summary(definition['stdout'])})
    for user in ('root', 'azureuser'):
        crontab = run(['sudo', '-n', 'crontab', '-u', user, '-l'])
        result['cron'].append({'source': 'crontab:' + user, 'exit': crontab['exit'],
                              'no_crontab': crontab['exit'] == 1 and 'no crontab' in crontab['stderr'],
                              'active_lines': len([s for s in crontab['stdout'].splitlines() if s.strip() and not s.lstrip().startswith('#')]),
                              **summary(crontab['stdout'])})
    for path in [Path('/etc/crontab'), *sorted(Path('/etc/cron.d').glob('*')),
                 *[f for d in ('hourly', 'daily', 'weekly', 'monthly') for f in sorted(Path('/etc/cron.' + d).glob('*'))]]:
        if not path.is_file():
            continue
        try:
            content = path.read_text()
            result['cron'].append({'source': str(path), 'read': True, **summary(content)})
        except (OSError, UnicodeError):
            result['cron'].append({'source': str(path), 'read': False})
    at = run(['sudo', '-n', 'atq'])
    result['at'] = {'exit': at['exit'], 'queued_jobs': len(at['stdout'].splitlines()) if at['exit'] == 0 else None,
                    'not_available': at['exit'] is None or 'command not found' in at['stderr']}
    apt = run(['apt-config', 'dump'])
    result['apt_automatic_reboot'] = {'exit': apt['exit'], 'settings': [line for line in apt['stdout'].splitlines() if re.match(r'Unattended-Upgrade::Automatic-Reboot(?:\s|\-|::)', line)]}
    for label, args in [('user_timers', ['systemctl', '--user', 'list-timers', '--all', '--no-pager', '--output=json']),
                        ('shutdown_targets', ['systemctl', 'show', 'shutdown.target', 'reboot.target', 'poweroff.target', '--property=Id,ActiveState,Job'])]:
        value = run(args)
        result[label] = {'exit': value['exit'], 'output': value['stdout']}
    return result


class ReadOnlyKubernetes(core.Kubernetes):
    """Uses the production watchdog engine but removes its mutation capability."""
    def __init__(self, context, namespace, evidence):
        super().__init__(context, namespace, command=self.read_command)
        self.evidence = Path(evidence)

    @staticmethod
    def read_command(args):
        index = args.index('kubectl') + 1
        tail = args[index:]
        # Every caller is generated by Kubernetes; fail before any mutation command.
        core.require(not any(token in tail for token in ('patch', 'scale', 'delete', 'apply', 'create', 'replace', 'edit')),
                     'Mutation forbidden in independent canary')
        return core.Kubernetes._command(args)

    def scale(self, state, replicas):
        core.require(state['context'] == self.context and state['namespace'] == self.namespace,
                     'Canary scope mismatch')
        core.require(replicas == state['replicas'] == 1, 'Canary cannot scale')
        core.require(self.ready(state), 'Worker changed; read-only canary cannot restore it')
        core.atomic_file(self.evidence / 'readonly-noop-observed.json',
                         {'uid': state['uid'], 'replicas': 1, 'scale_mutations': 0,
                          'mono': time.monotonic(), 'material': 'REAL_READ_ONLY_WATCHDOG_NOOP'})


def watchdog_child(state_file):
    path = Path(state_file)
    state = core.read_private(path, core.actor_identity())
    core.watchdog(path, kube=ReadOnlyKubernetes(state['context'], state['namespace'], path.parent))


def probe(parent, state):
    e = core.Evidence(Path(parent) / 'watchdog-readonly-probe')
    identity = e.identity
    start = time.monotonic()
    state = {**state, 'identity': identity, 'boot_id': core.boot_id(), 'run': uuid.uuid4().hex,
             'degraded_mono': start, 'deadline_mono': start + core.LIMIT}
    e.json('restore-state.json', state)
    core.atomic_file(e.root / 'heartbeat.json', {'mono': start}, identity)
    unit = 'met07-readonly-' + state['run']
    # The independent process receives no application credentials and has no patch code path.
    launch = run(['sudo', '-n', 'systemd-run', '--unit', unit, '--collect',
                  '--property=Restart=no', '--property=RuntimeMaxSec=50s', '--property=TimeoutStopSec=5s',
                  '--property=User=' + str(identity['uid']), '--property=Group=' + str(identity['gid']),
                  '--property=UMask=0077', '/usr/bin/python3', '-B', str(Path(__file__).resolve()),
                  'watchdog', str(e.root / 'restore-state.json')])
    e.json('launch.json', {'unit': unit, 'exit': launch['exit'], 'material': 'REAL_READ_ONLY_SYSTEMD_CANARY'})
    core.require(launch['exit'] == 0, 'Read-only canary launch failed')
    until = time.monotonic() + 5
    while not (e.root / 'guard-ready.json').exists():
        core.require(time.monotonic() < until, 'Read-only canary ACK timeout')
        time.sleep(.1)
    ack = core.read_private(e.root / 'guard-ready.json', identity)
    core.require(ack == {'run': state['run'], 'uid': state['uid'], 'identity': identity}, 'Foreign canary ACK')
    properties = run(['systemctl', 'show', unit, '--property=MainPID,User,Group,UMask,ActiveState,SubState,Restart,RuntimeMaxUSec'])
    e.json('independent-unit.json', {'exit': properties['exit'], 'properties': properties['stdout'],
                                   'supervisor_pid': os.getpid(), 'boot_id': core.boot_id()})
    k = ReadOnlyKubernetes(state['context'], state['namespace'], e.root)
    until = start + core.LEASE + 15
    while not (e.root / 'guard-restored.json').exists():
        core.require(k.ready(state), 'Worker changed during independent canary')
        core.require(time.monotonic() < until, 'Read-only canary lease timeout')
        time.sleep(.5)
    restored = core.read_private(e.root / 'guard-restored.json', identity)
    noop = core.read_private(e.root / 'readonly-noop-observed.json', identity)
    core.require(restored['run'] == state['run'] and restored['uid'] == state['uid'] and
                 restored['reason'] == 'lost-supervisor' and restored['within_deadline'] and
                 noop['scale_mutations'] == 0 and k.ready(state), 'Read-only canary validation failed')
    result = {'passed': True, 'material': 'REAL_INDEPENDENT_WATCHDOG_READ_ONLY_BACKEND',
              'production_engine': True, 'production_mutation_backend': False, 'real_restore_proven': False,
              'scale_mutations': 0, 'device_writes': 0, 'load_attempts': 0,
              'ack_identity_run_uid_verified': True, 'lease_reason': restored['reason'],
              'lease_elapsed_seconds': restored['mono'] - start, 'unit': unit}
    e.json('validation.json', result)
    return result


if __name__ == '__main__':
    os.umask(0o077)
    core.require(len(sys.argv) == 3 and sys.argv[1] == 'watchdog', 'Only read-only watchdog child CLI allowed')
    watchdog_child(sys.argv[2])
